#ifndef RELAY_MANAGER_H
#define RELAY_MANAGER_H

#include <Arduino.h>
#include "config.h"

/**
 * @file RelayManager.h
 * @brief Класс для управления исполнительными устройствами (реле).
 */

/**
 * @class RelayManager
 * @brief Менеджер управления твердотельными реле вентилятора и озонатора.
 *
 * Класс обеспечивает безопасное управление нагрузкой. Для вентилятора реализована
 * программная защита от "дребезга" (слишком частого переключения), которая
 * предотвращает выход двигателя из строя при быстро меняющихся показаниях датчиков.
 */
class RelayManager {
 private:
  bool fan_state_;    ///< Текущее логическое состояние вентилятора (true - включен).
  bool ozone_state_;  ///< Текущее логическое состояние озонатора (true - включен).

  /**
   * @brief Время последнего изменения состояния вентилятора (мс).
   * Используется для соблюдения интервала защиты двигателя.
   */
  unsigned long last_fan_change_time_;

  /**
   * @brief Минимальный интервал между переключениями вентилятора (5 минут).
   * Защищает обмотки двигателя от перегрева при частом старт-стопе.
   */
  const unsigned long kFanDebounceDelay = 300000UL;

 public:
  /**
   * @brief Конструктор. Инициализирует начальные состояния флагов.
   */
  RelayManager();

  /**
   * @brief Инициализация аппаратной части.
   * Настраивает пины на выход и устанавливает начальное безопасное состояние (выключено).
   */
  void Init();

  /**
   * @brief Управление вентилятором с защитой от частого переключения.
   *
   * Если с момента последнего переключения прошло менее 5 минут, команда игнорируется,
   * если не установлен флаг force.
   *
   * @param requested_state Желаемое состояние: true - включить, false - выключить.
   * @param force Принудительное переключение (игнорируя таймер защиты). Используется для аварийного отключения.
   */
  void SetFan(bool requested_state, bool force = false);

  /**
   * @brief Управление озонатором.
   *
   * Озонатор переключается мгновенно без дополнительных задержек в этом классе,
   * так как временные циклы озонирования контролируются внешним FSM.
   *
   * @param requested_state Желаемое состояние: true - включить, false - выключить.
   */
  void SetOzone(bool requested_state);

  /**
   * @brief Возвращает текущий статус вентилятора.
   * @return true Вентилятор включен.
   */
  bool GetFanState() const { return fan_state_; }

  /**
   * @brief Возвращает текущий статус озонатора.
   * @return true Озонатор включен.
   */
  bool GetOzoneState() const { return ozone_state_; }
};

#endif
