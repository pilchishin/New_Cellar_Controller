#ifndef MENU_DISPATCHER_H
#define MENU_DISPATCHER_H

#include <Arduino.h>
#include "ButtonEngine.h"

class DisplayUI;

/**
 * @file MenuDispatcher.h
 * @brief Определение класса MenuDispatcher, отвечающего за распределение событий кнопок.
 */

/**
 * @class MenuDispatcher
 * @brief Диспетчер событий меню, осуществляющий маршрутизацию нажатий кнопок.
 *
 * Класс анализирует текущее состояние навигации в интерфейсе (находится ли пользователь
 * в корневом меню или в подменю настройки параметра) и сопоставляет событие кнопки
 * (нажатие, удержание) с соответствующим идентификатором действия (ActionID).
 */
class MenuDispatcher {
 public:
  /**
   * @brief Обрабатывает событие кнопки и выполняет связанное с ним действие.
   *
   * Метод определяет, какое действие должно быть выполнено в текущем контексте меню
   * на основе переданного события кнопки. Если действие найдено, оно передается
   * в MenuActions::Execute для выполнения.
   *
   * @param ui Указатель на объект пользовательского интерфейса (DisplayUI).
   * @param event Тип события кнопки (вверх, вниз, меню, длинное нажатие и т.д.).
   */
  void Dispatch(DisplayUI* ui, ButtonEvent event);
};

#endif
