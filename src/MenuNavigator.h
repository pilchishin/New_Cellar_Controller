#ifndef MENU_NAVIGATOR_H
#define MENU_NAVIGATOR_H

#include <Arduino.h>

/**
 * @file MenuNavigator.h
 * @brief Определение класса MenuNavigator для управления состоянием навигации.
 */

/**
 * @class MenuNavigator
 * @brief Класс, инкапсулирующий состояние и логику навигации по иерархическому меню.
 *
 * Отвечает за хранение текущих индексов (корневая страница, элемент подменю)
 * и управление переходами между ними. Также отслеживает, находится ли пользователь
 * в режиме глубокой настройки (в подменю).
 */
class MenuNavigator {
 public:
  /**
   * @brief Конструктор по умолчанию. Инициализирует навигацию с начальной страницы.
   */
  MenuNavigator();

  /**
   * @brief Возвращает индекс текущей корневой страницы меню.
   * @return uint8_t Индекс в массиве ROOT_PAGES.
   */
  uint8_t GetRootIndex() const { return root_index_; }

  /**
   * @brief Возвращает индекс текущего элемента внутри подменю.
   * @return uint8_t Индекс в массиве настроек выбранной страницы.
   */
  uint8_t GetItemIndex() const { return item_index_; }

  /**
   * @brief Проверяет, активен ли режим подменю (редактирование параметра).
   * @return true Если пользователь находится внутри подменю.
   * @return false Если пользователь находится в основном навигационном меню.
   */
  bool InSubmenu() const { return in_submenu_; }

  /**
   * @brief Переходит к следующей корневой странице.
   * Сбрасывает состояние подменю и индекс элемента.
   * @param table_size Общее количество страниц в корневом меню.
   */
  void NextRoot(uint8_t table_size);

  /**
   * @brief Переходит к предыдущей корневой странице.
   * Сбрасывает состояние подменю и индекс элемента.
   * @param table_size Общее количество страниц в корневом меню.
   */
  void PrevRoot(uint8_t table_size);

  /**
   * @brief Переходит к следующему элементу внутри подменю.
   * @param item_count Количество элементов в текущем подменю.
   */
  void NextItem(uint8_t item_count);

  /**
   * @brief Переходит к предыдущему элементу внутри подменю.
   * @param item_count Количество элементов в текущем подменю.
   */
  void PrevItem(uint8_t item_count);

  /**
   * @brief Активирует режим подменю.
   */
  void EnterSubmenu();

  /**
   * @brief Деактивирует режим подменю и возвращает в основной список страниц.
   */
  void ExitSubmenu();

  /**
   * @brief Устанавливает индекс текущего элемента напрямую.
   * Используется для сброса или инициализации состояния при переходе между режимами.
   * @param index Новый индекс элемента.
   */
  void SetItemIndex(uint8_t index) { item_index_ = index; }

 private:
  uint8_t root_index_;  ///< Индекс активной страницы корневого меню.
  uint8_t item_index_;  ///< Индекс активного элемента (например, изменяемый разряд или параметр).
  bool in_submenu_;     ///< Флаг нахождения в режиме редактирования/подменю.
};

#endif
